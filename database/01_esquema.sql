-- UrbanCloud AI: esquema de base de datos (PostgreSQL 15 o superior).
-- Ejecutar en una base vacía. Crea las 20 tablas de la aplicación.
-- Los identificadores UUID los genera la aplicación; no se necesitan extensiones.
BEGIN;

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    descripcion TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE TABLE areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE TABLE prioridades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    nivel SMALLINT NOT NULL UNIQUE CHECK (nivel BETWEEN 1 AND 3)
);

CREATE TABLE estados_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    descripcion TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE TABLE distritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    provincia VARCHAR(255) NOT NULL,
    departamento VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    CONSTRAINT distritos_nombre_provincia_departamento_unico UNIQUE (nombre, provincia, departamento)
);

CREATE TABLE configuraciones_sistema (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave VARCHAR(255) NOT NULL UNIQUE,
    valor TEXT NOT NULL,
    descripcion TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    email_verified_at TIMESTAMPTZ,
    password VARCHAR(255) NOT NULL,
    rol_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    area_id BIGINT REFERENCES areas(id) ON DELETE SET NULL,
    activo BOOLEAN NOT NULL DEFAULT true,
    remember_token VARCHAR(100),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE TABLE incidencias (
    id UUID PRIMARY KEY,
    codigo VARCHAR(255) NOT NULL UNIQUE,
    ciudadano_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    titulo VARCHAR(255) NOT NULL,
    descripcion TEXT NOT NULL,
    categoria_id BIGINT REFERENCES categorias(id) ON DELETE RESTRICT,
    prioridad_id BIGINT REFERENCES prioridades(id) ON DELETE RESTRICT,
    area_id BIGINT REFERENCES areas(id) ON DELETE RESTRICT,
    estado_id BIGINT NOT NULL REFERENCES estados_incidencia(id) ON DELETE RESTRICT,
    distrito_id BIGINT NOT NULL REFERENCES distritos(id) ON DELETE RESTRICT,
    direccion VARCHAR(255) NOT NULL,
    latitud NUMERIC(10, 7) CHECK (latitud IS NULL OR latitud BETWEEN -90 AND 90),
    longitud NUMERIC(10, 7) CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180),
    fecha_limite TIMESTAMPTZ,
    fecha_cierre TIMESTAMPTZ,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE INDEX incidencias_estado_distrito_idx ON incidencias (estado_id, distrito_id);
CREATE INDEX incidencias_area_prioridad_idx ON incidencias (area_id, prioridad_id);
CREATE INDEX incidencias_ciudadano_fecha_idx ON incidencias (ciudadano_id, created_at);

CREATE TABLE validaciones_reporte (
    id UUID PRIMARY KEY,
    ciudadano_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    incidencia_id UUID REFERENCES incidencias(id) ON DELETE RESTRICT,
    titulo VARCHAR(255) NOT NULL,
    descripcion TEXT NOT NULL,
    ruta_imagen VARCHAR(255) NOT NULL,
    es_valido BOOLEAN NOT NULL,
    motivo TEXT,
    confianza NUMERIC(5, 4) CHECK (confianza IS NULL OR confianza BETWEEN 0 AND 1),
    respuesta_modelo JSONB,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    CONSTRAINT validaciones_reporte_rechazo_sin_incidencia CHECK (es_valido OR incidencia_id IS NULL)
);
CREATE INDEX validaciones_reporte_ciudadano_fecha_idx ON validaciones_reporte (ciudadano_id, created_at);
CREATE INDEX validaciones_reporte_incidencia_idx ON validaciones_reporte (incidencia_id);

CREATE TABLE analisis_ia (
    id UUID PRIMARY KEY,
    incidencia_id UUID NOT NULL REFERENCES incidencias(id) ON DELETE RESTRICT,
    categoria_sugerida_id BIGINT REFERENCES categorias(id) ON DELETE RESTRICT,
    prioridad_sugerida_id BIGINT REFERENCES prioridades(id) ON DELETE RESTRICT,
    area_sugerida_id BIGINT REFERENCES areas(id) ON DELETE RESTRICT,
    confianza NUMERIC(5, 4) CHECK (confianza IS NULL OR confianza BETWEEN 0 AND 1),
    respuesta_modelo JSONB,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE INDEX analisis_ia_incidencia_fecha_idx ON analisis_ia (incidencia_id, created_at);

CREATE TABLE evidencias_incidencia (
    id UUID PRIMARY KEY,
    incidencia_id UUID NOT NULL REFERENCES incidencias(id) ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('REPORTE', 'ATENCION', 'CIERRE', 'OTRA')),
    ruta_archivo VARCHAR(255) NOT NULL,
    descripcion TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE INDEX evidencias_incidencia_tipo_idx ON evidencias_incidencia (incidencia_id, tipo);

CREATE TABLE historial_estados_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id UUID NOT NULL REFERENCES incidencias(id) ON DELETE RESTRICT,
    estado_anterior_id BIGINT REFERENCES estados_incidencia(id) ON DELETE RESTRICT,
    estado_nuevo_id BIGINT NOT NULL REFERENCES estados_incidencia(id) ON DELETE RESTRICT,
    cambiado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    comentario TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX historial_estados_incidencia_fecha_idx ON historial_estados_incidencia (incidencia_id, created_at);

CREATE TABLE asignaciones_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id UUID NOT NULL REFERENCES incidencias(id) ON DELETE RESTRICT,
    tecnico_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    asignado_por BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    fecha_asignacion TIMESTAMPTZ NOT NULL,
    fecha_fin TIMESTAMPTZ,
    activa BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    CONSTRAINT asignaciones_incidencia_fechas_validas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_asignacion)
);
CREATE UNIQUE INDEX asignaciones_incidencia_una_activa
    ON asignaciones_incidencia (incidencia_id) WHERE activa = true;
CREATE INDEX asignaciones_incidencia_tecnico_activa_idx ON asignaciones_incidencia (tecnico_id, activa);

CREATE TABLE actualizaciones_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id UUID NOT NULL REFERENCES incidencias(id) ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    estado_id BIGINT REFERENCES estados_incidencia(id) ON DELETE RESTRICT,
    comentario TEXT NOT NULL,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE INDEX actualizaciones_incidencia_fecha_idx ON actualizaciones_incidencia (incidencia_id, created_at);

CREATE TABLE seguidores_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id UUID NOT NULL REFERENCES incidencias(id) ON DELETE RESTRICT,
    ciudadano_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    CONSTRAINT seguidores_incidencia_unico UNIQUE (incidencia_id, ciudadano_id)
);

CREATE TABLE notificaciones_incidencia (
    id UUID PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    incidencia_id UUID REFERENCES incidencias(id) ON DELETE SET NULL,
    titulo VARCHAR(255) NOT NULL,
    mensaje TEXT NOT NULL,
    leida_en TIMESTAMPTZ,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE INDEX notificaciones_incidencia_usuario_lectura_idx ON notificaciones_incidencia (usuario_id, leida_en);

CREATE TABLE auditorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    incidencia_id UUID REFERENCES incidencias(id) ON DELETE RESTRICT,
    accion VARCHAR(255) NOT NULL,
    entidad VARCHAR(255) NOT NULL,
    entidad_id VARCHAR(255),
    valores_anteriores JSONB,
    valores_nuevos JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX auditorias_entidad_idx ON auditorias (entidad, entidad_id);
CREATE INDEX auditorias_incidencia_fecha_idx ON auditorias (incidencia_id, created_at);

-- Tablas de autenticación del backend FastAPI (migraciones Alembic 0002 y 0003).
CREATE TABLE IF NOT EXISTS sesiones_renovacion (
    id UUID PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    vence_en TIMESTAMPTZ NOT NULL,
    revocada_en TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS tokens_correo (
    id UUID PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    proposito VARCHAR(20) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    vence_en TIMESTAMPTZ NOT NULL,
    usado_en TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_tokens_correo_usuario_id ON tokens_correo (usuario_id);

-- Seguridad por filas (RLS) en las 20 tablas. El backend se conecta directamente por PostgreSQL
-- con el usuario propietario, que no se ve afectado. Sin politicas, la API publica de Supabase
-- (roles anon y authenticated) no puede leer ni escribir ninguna tabla.
ALTER TABLE roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE areas ENABLE ROW LEVEL SECURITY;
ALTER TABLE categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE prioridades ENABLE ROW LEVEL SECURITY;
ALTER TABLE estados_incidencia ENABLE ROW LEVEL SECURITY;
ALTER TABLE distritos ENABLE ROW LEVEL SECURITY;
ALTER TABLE configuraciones_sistema ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE incidencias ENABLE ROW LEVEL SECURITY;
ALTER TABLE validaciones_reporte ENABLE ROW LEVEL SECURITY;
ALTER TABLE analisis_ia ENABLE ROW LEVEL SECURITY;
ALTER TABLE evidencias_incidencia ENABLE ROW LEVEL SECURITY;
ALTER TABLE historial_estados_incidencia ENABLE ROW LEVEL SECURITY;
ALTER TABLE asignaciones_incidencia ENABLE ROW LEVEL SECURITY;
ALTER TABLE actualizaciones_incidencia ENABLE ROW LEVEL SECURITY;
ALTER TABLE seguidores_incidencia ENABLE ROW LEVEL SECURITY;
ALTER TABLE notificaciones_incidencia ENABLE ROW LEVEL SECURITY;
ALTER TABLE auditorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE sesiones_renovacion ENABLE ROW LEVEL SECURITY;
ALTER TABLE tokens_correo ENABLE ROW LEVEL SECURITY;

COMMIT;
